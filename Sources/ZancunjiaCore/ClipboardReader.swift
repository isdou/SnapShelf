import AppKit
import UniformTypeIdentifiers

public enum MediaPayload: Sendable {
    case image(data: Data, sourceURL: URL?)
    case video(fileURL: URL, width: Int, height: Int, duration: TimeInterval, thumbnailPNG: Data)
    case livePhoto(imageURL: URL, videoURL: URL, width: Int, height: Int, duration: TimeInterval, thumbnailPNG: Data)
}

public enum ClipboardReader {
    private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    private static let imageTypes: [NSPasteboard.PasteboardType] = [
        .png,
        .tiff,
        NSPasteboard.PasteboardType("public.jpeg"),
        NSPasteboard.PasteboardType("public.heic"),
        NSPasteboard.PasteboardType("public.gif"),
        NSPasteboard.PasteboardType("public.webp"),
        NSPasteboard.PasteboardType("Apple PNG pasteboard type"),
    ]

    private static let videoTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("com.apple.quicktime-movie"),
        NSPasteboard.PasteboardType("public.mpeg-4"),
        NSPasteboard.PasteboardType("public.movie"),
        NSPasteboard.PasteboardType("public.video"),
    ]

    /// Legacy method for raw image data extraction.
    public static func payloads(from pasteboard: NSPasteboard, limit: Int = 12) -> [Data] {
        guard !shouldIgnore(pasteboard) else { return [] }
        var found: [Data] = []

        if let urls = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: nil
        ) as? [URL] {
            for url in urls where url.isFileURL {
                guard found.count < limit else { break }
                guard MediaExtractor.isImageFile(url) else { continue }
                guard let data = try? Data(contentsOf: url), !data.isEmpty else { continue }
                found.append(data)
            }
        }

        if found.isEmpty {
            for type in imageTypes {
                guard let data = pasteboard.data(forType: type), !data.isEmpty else { continue }
                found.append(data)
                break
            }
        }

        if found.isEmpty,
           let images = pasteboard.readObjects(forClasses: [NSImage.self], options: nil) as? [NSImage] {
            for image in images {
                guard found.count < limit else { break }
                guard let tiff = image.tiffRepresentation, !tiff.isEmpty else { continue }
                found.append(tiff)
            }
        }

        return found
    }

    /// Primary reader: extracts images, videos, and Live Photos (intelligently paired).
    public static func readMedia(from pasteboard: NSPasteboard, limit: Int = 12) async -> [MediaPayload] {
        guard !shouldIgnore(pasteboard) else { return [] }
        var results: [MediaPayload] = []

        // 1. Read file URLs from pasteboard
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL] {
            let fileURLs = urls.filter(\.isFileURL)
            if !fileURLs.isEmpty {
                results = await parseFileURLs(fileURLs, limit: limit)
            }
        }

        if !results.isEmpty {
            return results
        }

        // 2. Check for raw video data
        for type in videoTypes {
            if let data = pasteboard.data(forType: type), !data.isEmpty {
                let tempFile = SessionCache.root.appending(path: "clip-\(UUID().uuidString).mov")
                if (try? FileManager.default.createDirectory(at: SessionCache.root, withIntermediateDirectories: true)) != nil,
                   (try? data.write(to: tempFile, options: .atomic)) != nil,
                   let info = await MediaExtractor.videoInfo(at: tempFile) {
                    results.append(.video(fileURL: tempFile, width: info.width, height: info.height, duration: info.duration, thumbnailPNG: info.thumbnailPNG))
                    return results
                }
                try? FileManager.default.removeItem(at: tempFile)
            }
        }

        // 3. Check for raw image data
        for type in imageTypes {
            if let data = pasteboard.data(forType: type), !data.isEmpty {
                results.append(.image(data: data, sourceURL: nil))
                return results
            }
        }

        // 4. Fallback to NSImage
        if let images = pasteboard.readObjects(forClasses: [NSImage.self], options: nil) as? [NSImage] {
            for image in images {
                guard results.count < limit else { break }
                guard let tiff = image.tiffRepresentation, !tiff.isEmpty else { continue }
                results.append(.image(data: tiff, sourceURL: nil))
            }
        }

        return results
    }

    public static func shouldIgnore(_ pasteboard: NSPasteboard) -> Bool {
        !privateTypes.isDisjoint(with: pasteboard.types ?? [])
    }

    private static func parseFileURLs(_ urls: [URL], limit: Int) async -> [MediaPayload] {
        var payloads: [MediaPayload] = []
        var imageCandidates: [URL] = []
        var movieCandidates: [URL] = []

        for url in urls {
            // Check if it's a Live Photo .pvt bundle directory
            if url.pathExtension.lowercased() == "pvt" || (try? url.resourceValues(forKeys: [.isDirectoryKey]).isDirectory) == true {
                if let inside = try? FileManager.default.contentsOfDirectory(at: url, includingPropertiesForKeys: nil) {
                    let img = inside.first { MediaExtractor.isImageFile($0) }
                    let mov = inside.first { MediaExtractor.isMovieFile($0) }
                    if let img, let mov {
                        if let info = await MediaExtractor.livePhotoInfo(imageURL: img, videoURL: mov) {
                            payloads.append(.livePhoto(
                                imageURL: img,
                                videoURL: mov,
                                width: info.width,
                                height: info.height,
                                duration: info.duration,
                                thumbnailPNG: info.thumbnailPNG
                            ))
                            continue
                        }
                    }
                }
            }

            if MediaExtractor.isImageFile(url) {
                imageCandidates.append(url)
            } else if MediaExtractor.isMovieFile(url) {
                movieCandidates.append(url)
            }
        }

        // Try to pair images and movies into Live Photos
        var pairedImageURLs = Set<URL>()
        var pairedMovieURLs = Set<URL>()

        for movieURL in movieCandidates {
            guard payloads.count < limit else { break }
            let movieBase = movieURL.deletingPathExtension().path.lowercased()
            let movieAssetID = await MediaExtractor.videoLivePhotoIdentifier(at: movieURL)

            // Find matching image
            var matchedImageURL: URL?
            for imageURL in imageCandidates where !pairedImageURLs.contains(imageURL) {
                let imageBase = imageURL.deletingPathExtension().path.lowercased()
                if imageBase == movieBase {
                    matchedImageURL = imageURL
                    break
                }
                if let movieAssetID, let imageAssetID = MediaExtractor.imageLivePhotoIdentifier(at: imageURL), movieAssetID == imageAssetID {
                    matchedImageURL = imageURL
                    break
                }
            }

            if let img = matchedImageURL {
                pairedImageURLs.insert(img)
                pairedMovieURLs.insert(movieURL)
                if let info = await MediaExtractor.livePhotoInfo(imageURL: img, videoURL: movieURL) {
                    payloads.append(.livePhoto(
                        imageURL: img,
                        videoURL: movieURL,
                        width: info.width,
                        height: info.height,
                        duration: info.duration,
                        thumbnailPNG: info.thumbnailPNG
                    ))
                }
            }
        }

        // Add remaining unpaired movies
        for movieURL in movieCandidates where !pairedMovieURLs.contains(movieURL) {
            guard payloads.count < limit else { break }
            if let info = await MediaExtractor.videoInfo(at: movieURL) {
                payloads.append(.video(
                    fileURL: movieURL,
                    width: info.width,
                    height: info.height,
                    duration: info.duration,
                    thumbnailPNG: info.thumbnailPNG
                ))
            }
        }

        // Add remaining unpaired images
        for imageURL in imageCandidates where !pairedImageURLs.contains(imageURL) {
            guard payloads.count < limit else { break }
            if let data = try? Data(contentsOf: imageURL), !data.isEmpty {
                payloads.append(.image(data: data, sourceURL: imageURL))
            }
        }

        return payloads
    }
}
